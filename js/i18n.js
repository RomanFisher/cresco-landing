// Функція безпосередньої зміни мови контенту
function changeLanguage(lang) {
    const elementsToTranslate = document.querySelectorAll('[data-lang-key]');
    
    elementsToTranslate.forEach(element => {
        const key = element.getAttribute('data-lang-key');
        if (translations[lang] && translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });

    // Оновлюємо активні класи на кнопках EN/PL
    const langButtons = document.querySelectorAll('.lang-btn');
    langButtons.forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Запам'ятовуємо мову
    localStorage.setItem('cresco_lang', lang);
}

// Ініціалізація мови при завантаженні скрипта
document.addEventListener('DOMContentLoaded', () => {
    const langButtons = document.querySelectorAll('.lang-btn');
    
    langButtons.forEach(button => {
        button.addEventListener('click', () => {
            const selectedLang = button.getAttribute('data-lang');
            changeLanguage(selectedLang);
        });
    });

    const savedLanguage = localStorage.getItem('cresco_lang') || 'en';
    changeLanguage(savedLanguage);
});